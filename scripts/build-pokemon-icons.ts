/*
Builds generation-based Pokemon icon tilesets and the species-to-icon manifest
from the 64x64 PNGs in src/assets/pokemon/source and Rust species IDs.
Run `bun run scripts/build-pokemon-icons.ts` after changing source icons or
species IDs. Requires ImageMagick (magick) on PATH.
*/

import fs from "node:fs/promises";
import { spawn } from "bun";
import { toNativeAbsolute } from "./path";

const source = toNativeAbsolute("../src/assets/pokemon/source");
const output = toNativeAbsolute("../src/assets/pokemon/tilesets");
const ends = [151, 251, 386, 493, 649, 721, 809];
const columns = 16;
const cellSize = 64;
const files = (await fs.readdir(source)).sort((left, right) =>
  left.localeCompare(right, "en", { numeric: true }),
);
const entries = files.map((file) => {
  const match = /^p(\d+)(?:-([a-z]+))?\.png$/.exec(file);
  if (match == null) {
    throw new Error(`Unexpected icon filename: ${file}`);
  }

  const dex = Number(match[1]);
  const sheet = ends.findIndex((end) => dex <= end);
  if (dex < 1 || sheet < 0) {
    throw new Error(`Unsupported icon: ${file}`);
  }

  return { file, dex, form: match[2], sheet };
});

for (const entry of entries) {
  const header = await fs.readFile(`${source}/${entry.file}`);
  const view = new DataView(
    header.buffer,
    header.byteOffset,
    Math.min(header.byteLength, 24),
  );
  if (
    view.byteLength !== 24 ||
    view.getUint32(0) !== 0x89504e47 ||
    view.getUint32(16) !== cellSize ||
    view.getUint32(20) !== cellSize
  ) {
    throw new Error(`Source icon must be a 64x64 PNG: ${entry.file}`);
  }
}

const locations = new Map<string, { sheet: number; index: number }>();
await fs.mkdir(output, { recursive: true });
const imports: string[] = [];
const sheets: string[] = [];

for (let sheet = 0; sheet < ends.length; sheet++) {
  const icons = entries.filter((entry) => entry.sheet === sheet);
  const rows = Math.ceil(icons.length / columns);
  const filename = `gen${sheet + 1}.webp`;
  const montageProcess = spawn(
    [
      "magick",
      "montage",
      ...icons.map((icon) => icon.file),
      "-background",
      "none",
      "-tile",
      `${columns}x${rows}`,
      "-geometry",
      "64x64+0+0",
      "-define",
      "webp:lossless=true",
      "-define",
      "webp:method=6",
      toNativeAbsolute(`../src/assets/pokemon/tilesets/${filename}`),
    ],
    { cwd: source, stdout: "inherit", stderr: "inherit" },
  );

  if ((await montageProcess.exited) !== 0) {
    throw new Error(`Failed to generate ${filename}`);
  }

  icons.forEach((icon, index) => {
    locations.set(icon.file, {
      sheet,
      index,
    });
  });
  sheets.push(
    `const gen${sheet + 1}: PokemonIconSheet = { url: gen${sheet + 1}Url, rows: ${rows} };`,
  );
  imports.push(
    `import gen${sheet + 1}Url from "~/assets/pokemon/tilesets/${filename}";`,
  );
}

// Species array indices include forms; use the explicit Rust IDs instead.
const rust = await fs.readFile(
  toNativeAbsolute("../rng_tools/src/pkm/species.rs"),
  "utf8",
);
const mappings: string[] = [];

for (const match of rust.matchAll(
  /^ {4}(\w+) = (?:spec_form\((\d+), (\d+)\)|(\d+)),/gm,
)) {
  const [, species, formDex, , plainDex] = match;
  // Alternate forms share the base species artwork.
  const location = locations.get(`p${formDex ?? plainDex}.png`);
  if (location != null) {
    const { sheet, index } = location;
    mappings.push(`  ${species}: [gen${sheet + 1}, ${index}],`);
  }
}

await fs.writeFile(
  toNativeAbsolute("../src/utils/pokemonIconManifest.ts"),
  `// Generated by bun run scripts/build-pokemon-icons.ts. Do not edit.\n` +
    `import type { Species } from "~/rngTools";\n` +
    `${imports.join("\n")}\n\n` +
    `export type PokemonIconSheet = { url: string; rows: number };\n\n` +
    `export type PokemonIconCell = readonly [sheet: PokemonIconSheet, index: number];\n\n` +
    `export const pokemonIconColumns = ${columns};\n\n` +
    `${sheets.join("\n")}\n\n` +
    `export const pokemonIconCells: Partial<Record<Species, PokemonIconCell>> = {\n${mappings.join("\n")}\n};\n`,
);
