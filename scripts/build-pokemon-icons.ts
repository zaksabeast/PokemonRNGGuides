import { mkdir, readdir } from "node:fs/promises";
import { resolve } from "node:path";

// Requires ImageMagick (magick) on PATH. No image processing runs in the app.
const root = resolve(import.meta.dir, "..");
const source = resolve(root, "src/assets/pokemon/source");
const output = resolve(root, "src/assets/pokemon/tilesets");
const ends = [151, 251, 386, 493, 649, 721, 809];
const columns = 16;
const cellSize = 64;
const files = (await readdir(source)).sort((a, b) =>
  a.localeCompare(b, "en", { numeric: true }),
);
const entries = files.map((file) => {
  const match = /^p(\d+)(?:-([a-z]+))?\.png$/.exec(file);
  if (!match) throw new Error(`Unexpected icon filename: ${file}`);
  const dex = Number(match[1]);
  const sheet = ends.findIndex((end) => dex <= end);
  if (dex < 1 || sheet < 0) throw new Error(`Unsupported icon: ${file}`);
  return { file, dex, form: match[2], sheet };
});
for (const entry of entries) {
  const header = await Bun.file(resolve(source, entry.file))
    .slice(0, 24)
    .arrayBuffer();
  const view = new DataView(header);
  if (
    view.byteLength !== 24 ||
    view.getUint32(0) !== 0x89504e47 ||
    view.getUint32(16) !== cellSize ||
    view.getUint32(20) !== cellSize
  ) {
    throw new Error(`Source icon must be a 64x64 PNG: ${entry.file}`);
  }
}
await mkdir(output, { recursive: true });
const locations = new Map<string, { sheet: number; x: number; y: number }>();
const imports: string[] = [];
const sheets: string[] = [];
for (let sheet = 0; sheet < ends.length; sheet++) {
  const icons = entries.filter((entry) => entry.sheet === sheet);
  const rows = Math.ceil(icons.length / columns);
  const filename = `gen${sheet + 1}.png`;
  const process = Bun.spawn(
    [
      "magick",
      "montage",
      ...icons.map((icon) => icon.file),
      "-background",
      "none",
      "-tile",
      `${columns}x${rows}`,
      "-geometry",
      "64x64+0+0",
      resolve(output, filename),
    ],
    { cwd: source, stdout: "inherit", stderr: "inherit" },
  );
  if ((await process.exited) !== 0)
    throw new Error(`Failed to generate ${filename}`);
  icons.forEach((icon, index) => {
    locations.set(icon.file, {
      sheet,
      x: (index % columns) * cellSize,
      y: Math.floor(index / columns) * cellSize,
    });
  });
  imports.push(
    `import gen${sheet + 1} from "~/assets/pokemon/tilesets/${filename}";`,
  );
  sheets.push(
    `  { src: gen${sheet + 1}, width: ${columns * cellSize}, height: ${rows * cellSize} },`,
  );
}
// Species array indices include forms; use the explicit Rust IDs instead.
const rust = await Bun.file(
  resolve(root, "rng_tools/src/pkm/species.rs"),
).text();
const mappings: string[] = [];
for (const match of rust.matchAll(
  /^    (\w+) = (?:spec_form\((\d+), (\d+)\)|(\d+)),/gm,
)) {
  const [, species, formDex, , plainDex] = match;
  // Alternate forms share the base species artwork.
  const location = locations.get(`p${formDex ?? plainDex}.png`);
  if (location) mappings.push(`  ${species}: ${JSON.stringify(location)},`);
}
await Bun.write(
  resolve(root, "src/utils/pokemonIconManifest.ts"),
  `// Generated by bun run scripts/build-pokemon-icons.ts. Do not edit.\n` +
    `import type { Species } from "~/rngTools";\n${imports.join("\n")}\n\n` +
    `export const pokemonIconSheets = [\n${sheets.join("\n")}\n];\n\n` +
    `export type PokemonIconLocation = { sheet: number; x: number; y: number };\n\n` +
    `export const pokemonIconManifest: Partial<Record<Species, PokemonIconLocation>> = {\n${mappings.join("\n")}\n};\n`,
);
console.log(
  `Packed ${entries.length} icons into ${ends.length} sheets; mapped ${mappings.length} species.`,
);
